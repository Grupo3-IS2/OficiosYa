package com.um.uy.oficiosya.entity;

import com.um.uy.oficiosya.config.ChatContentConverter;
import jakarta.persistence.*;
import jakarta.validation.constraints.AssertTrue;
import jakarta.validation.constraints.NotNull;
import lombok.*;
import org.hibernate.annotations.CreationTimestamp;

import java.time.OffsetDateTime;
import java.util.UUID;

@Entity
@Getter
@Setter
@Table(name = "chat_message", schema = "chat",
        uniqueConstraints = @UniqueConstraint(name = "uk_chat_message_client_message_id",
                columnNames = {"conversation_id", "sender_id", "client_message_id"}),
        indexes = @Index(name = "idx_chat_message_conversation_id", columnList = "conversation_id, id desc"))
@Builder
@NoArgsConstructor
@AllArgsConstructor
public class ChatMessage {
    /** Also the cursor the history is paged by. */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "conversation_id", nullable = false)
    private Conversation conversation;

    /** On a JOB_PROPOSAL, whoever proposed the job. */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "sender_id", nullable = false)
    private Client sender;

    @NotNull
    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 32)
    private ChatMessageType type;

    /** The text of a TEXT message, encrypted at rest; null on a JOB_PROPOSAL, whose card is read from the job. */
    @Convert(converter = ChatContentConverter.class)
    @Column(columnDefinition = "text")
    private String content;

    /** Optional on a TEXT message (the job it's about), required on a JOB_PROPOSAL (the job proposed). */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "job_request_id")
    private JobRequest jobRequest;

    /** Generated by the frontend for a TEXT message, so a retried send doesn't store it twice. */
    @NotNull
    @Column(nullable = false)
    private UUID clientMessageId;

    @CreationTimestamp
    @Column(nullable = false, updatable = false)
    private OffsetDateTime createdAt;

    /** Checked by Bean Validation before every insert and update. */
    @AssertTrue(message = "Un mensaje de texto lleva contenido y una propuesta lleva el trabajo, sin contenido")
    public boolean isConsistentWithType() {
        return type != ChatMessageType.JOB_PROPOSAL
                ? content != null
                : jobRequest != null && content == null;
    }
}
